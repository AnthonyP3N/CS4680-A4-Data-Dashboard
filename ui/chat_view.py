STATUS_LABELS = {
    "answer": "Answered", "clarify": "Asked for clarification", "unsupported": "Not answerable from this data",
    "blocked": "Blocked by a safety check", "error": "Failed", "needs_confirmation": "Waiting for confirmation",
    "committed": "Change applied", "cancelled": "Change cancelled", "noted": "Saved to memory",
}
SAVE_KINDS = {"Result": "result", "Chart": "chart", "Query": "query"}
GENERATED_NOTE = "Answers are analyses generated by an AI model. Check the SQL behind important figures."

FOLLOW_UP_STATUSES = ("answer", "clarify", "unsupported", "committed")

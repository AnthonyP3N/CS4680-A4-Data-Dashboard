"""Exporting conversations as JSON, Markdown or print-ready HTML.

Exports are built from what is stored, never from what happens to be on screen.
So an export contains exactly what AskData was allowed to keep: result rows
that weren't saved (because they included a sensitive column, or saving results
is off) are absent from every format, and hidden earlier versions of an answer
are left out.
"""

from __future__ import annotations

import html
import json
from datetime import datetime, timezone
from typing import Any, Sequence

from storage.models import Conversation, Message

FORMAT = "askdata.conversation"
FORMAT_VERSION = 1
DISCLAIMER = ("Answers are analyses generated by an AI model from the SQL shown. "
              "Check important figures against the query before relying on them.")
MARKDOWN_ROWS = 50
HTML_ROWS = 200


# --------------------------------------------------------------------------- #
# The document (also the JSON format)
# --------------------------------------------------------------------------- #
def conversation_document(conversation: Conversation, messages: Sequence[Message], *, source_name: str = "",
                          tags: Sequence[str] = (), exported_at: str | None = None) -> dict[str, Any]:
    """One conversation as plain data. `messages` are its visible messages in order."""
    users = {m.id: m for m in messages if m.role == "user"}
    turns = []
    for answer in (m for m in messages if m.role == "assistant" and m.parent_message_id in users):
        question = users[answer.parent_message_id]
        meta = answer.result_metadata
        preview = meta.get("preview") or {}
        turns.append({
            "question": question.content,
            "asked_at": question.created_at,
            "status": answer.status,
            "intent": answer.intent,
            "explanation": answer.explanation,
            "sql": answer.sql,
            "chart": answer.chart_spec or None,
            "row_count": meta.get("row_count"),
            "columns": preview.get("columns") or meta.get("columns") or [],
            "rows": preview.get("rows"),                       # None when the rows were not saved
            "rows_truncated": bool(preview.get("truncated")),
            "rows_not_saved_reason": (None if preview else
                                      "sensitive column" if meta.get("sensitive_columns") else
                                      "not saved" if answer.status == "answer" else None),
            "notes": meta.get("notes") or [],
            "error": meta.get("error") or "",
            "data_source": meta.get("source_name") or source_name,
            "model": answer.model,
            "elapsed_ms": meta.get("elapsed_ms"),
            "execution_ms": meta.get("execution_ms"),
        })
    return {
        "format": FORMAT, "version": FORMAT_VERSION,
        "exported_at": exported_at or datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "title": conversation.title, "category": conversation.category, "tags": list(tags),
        "data_source": source_name, "created_at": conversation.created_at,
        "last_message_at": conversation.last_message_at, "archived": conversation.archived,
        "pinned": conversation.pinned, "disclaimer": DISCLAIMER, "turns": turns,
    }


def to_json(document: dict[str, Any] | list[dict[str, Any]]) -> str:
    return json.dumps(document, indent=2, default=str, ensure_ascii=False)


def workspace_document(workspace_name: str, documents: Sequence[dict[str, Any]]) -> dict[str, Any]:
    """Every conversation in a workspace, for a full history export."""
    return {"format": "askdata.workspace", "version": FORMAT_VERSION, "workspace": workspace_name,
            "exported_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "disclaimer": DISCLAIMER, "conversations": list(documents)}


# --------------------------------------------------------------------------- #
# Markdown
# --------------------------------------------------------------------------- #
STATUS_LABELS = {
    "answer": "Answered", "clarify": "Asked for clarification", "unsupported": "Not answerable from this data",
    "blocked": "Blocked by a safety check", "error": "Failed", "needs_confirmation": "Change waiting for confirmation",
    "committed": "Change applied", "cancelled": "Change cancelled", "noted": "Saved to memory",
}


def _one_line(text: Any) -> str:
    return " ".join(str(text).split())


def _md_cell(value: Any) -> str:
    return "" if value is None else _one_line(value).replace("|", "\\|")


def _summary(turn: dict[str, Any]) -> str:
    parts = [STATUS_LABELS.get(turn["status"], turn["status"])]
    if turn.get("row_count") is not None and turn["status"] == "answer":
        parts.append(f"{turn['row_count']:,} row{'s' if turn['row_count'] != 1 else ''}")
    if turn.get("data_source"):
        parts.append(turn["data_source"])
    if turn.get("model"):
        parts.append(turn["model"])
    return " | ".join(parts)


def _rows_note(turn: dict[str, Any], shown: int) -> str:
    if turn["rows"] is None:
        if turn["rows_not_saved_reason"] == "sensitive column":
            return "Result rows were not saved because the query reads a column marked sensitive."
        return "Result rows were not saved with this conversation." if turn["rows_not_saved_reason"] else ""
    total = turn.get("row_count") or len(turn["rows"])
    return f"Showing {shown:,} of {total:,} rows." if shown < total else ""


def to_markdown(document: dict[str, Any]) -> str:
    lines = [f"# {_one_line(document['title'])}", ""]
    meta = [f"Data source: {document['data_source']}" if document.get("data_source") else "",
            f"Category: {document['category']}" if document.get("category") else "",
            f"Tags: {', '.join(document['tags'])}" if document.get("tags") else "",
            f"Exported: {document['exported_at']}"]
    lines += ["  \n".join(m for m in meta if m), "", f"> {DISCLAIMER}", ""]
    for number, turn in enumerate(document["turns"], start=1):
        lines += [f"## {number}. {_one_line(turn['question'])}", "", f"*{_summary(turn)}*", ""]
        if turn["explanation"]:
            lines += [turn["explanation"].strip(), ""]
        if turn["error"]:
            lines += [f"**Problem:** {_one_line(turn['error'])}", ""]
        if turn["sql"]:
            lines += ["```sql", turn["sql"].strip(), "```", ""]
        if turn["rows"]:
            shown = turn["rows"][:MARKDOWN_ROWS]
            lines.append("| " + " | ".join(_md_cell(c) for c in turn["columns"]) + " |")
            lines.append("|" + "|".join(" --- " for _ in turn["columns"]) + "|")
            lines += ["| " + " | ".join(_md_cell(v) for v in row) + " |" for row in shown]
            lines.append("")
        note = _rows_note(turn, len((turn["rows"] or [])[:MARKDOWN_ROWS]))
        if note:
            lines += [f"*{note}*", ""]
        for extra in turn["notes"]:
            lines += [f"- {_one_line(extra)}"]
        if turn["notes"]:
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


# --------------------------------------------------------------------------- #
# HTML (opens in any browser; "Print" then "Save as PDF" gives a clean PDF)
# --------------------------------------------------------------------------- #
_CSS = """
body{font:15px/1.55 system-ui,-apple-system,"Segoe UI",sans-serif;color:#1B2333;max-width:860px;margin:2.5rem auto;padding:0 1.25rem}
h1{font-size:1.7rem;margin:0 0 .3rem;letter-spacing:-.01em}
h1 span{background:linear-gradient(transparent 60%,#FFD84D 60%,#FFD84D 92%,transparent 92%)}
.meta,.small{color:#5B6475;font-size:.88rem}
.disclaimer{border-left:3px solid #5B6475;padding:.5rem .8rem;margin:1rem 0 1.6rem;color:#5B6475;font-size:.9rem}
.turn{margin:0 0 1.8rem;padding-top:1.1rem;border-top:1px solid #DCE0E8;break-inside:avoid}
h2{font-size:1.12rem;margin:0 0 .25rem}
pre{background:#F2F4F8;padding:.7rem .9rem;border-radius:8px;overflow-x:auto;font:13px/1.45 ui-monospace,Menlo,Consolas,monospace;white-space:pre-wrap}
table{border-collapse:collapse;width:100%;font-size:.86rem;margin:.6rem 0}
th,td{border:1px solid #DCE0E8;padding:.28rem .5rem;text-align:left;vertical-align:top}
th{background:#F2F4F8}
.problem{color:#C2410C}
@media print{body{margin:0;max-width:none}pre{white-space:pre-wrap}a{color:inherit}}
"""


def to_html(document: dict[str, Any]) -> str:
    """A self-contained page with no scripts and no external files. Every value is escaped."""
    e = lambda value: html.escape("" if value is None else str(value))   # noqa: E731
    meta = [f"Data source: {e(document['data_source'])}" if document.get("data_source") else "",
            f"Category: {e(document['category'])}" if document.get("category") else "",
            f"Tags: {e(', '.join(document['tags']))}" if document.get("tags") else "",
            f"Exported: {e(document['exported_at'])}"]
    parts = ["<!doctype html>", '<html lang="en"><head><meta charset="utf-8">',
             '<meta name="viewport" content="width=device-width, initial-scale=1">',
             f"<title>{e(document['title'])}</title><style>{_CSS}</style></head><body>",
             f"<h1><span>{e(document['title'])}</span></h1>",
             f'<p class="meta">{" &middot; ".join(m for m in meta if m)}</p>',
             f'<p class="disclaimer">{e(DISCLAIMER)}</p>']
    for number, turn in enumerate(document["turns"], start=1):
        parts.append('<section class="turn">')
        parts.append(f"<h2>{number}. {e(turn['question'])}</h2>")
        parts.append(f'<p class="small">{e(_summary(turn))}</p>')
        if turn["explanation"]:
            parts.append(f"<p>{e(turn['explanation'])}</p>")
        if turn["error"]:
            parts.append(f'<p class="problem">{e(turn["error"])}</p>')
        if turn["sql"]:
            parts.append(f"<pre>{e(turn['sql'].strip())}</pre>")
        shown = (turn["rows"] or [])[:HTML_ROWS]
        if shown:
            head = "".join(f"<th>{e(c)}</th>" for c in turn["columns"])
            body = "".join("<tr>" + "".join(f"<td>{e(v)}</td>" for v in row) + "</tr>" for row in shown)
            parts.append(f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>")
        note = _rows_note(turn, len(shown))
        if note:
            parts.append(f'<p class="small">{e(note)}</p>')
        if turn["notes"]:
            parts.append("<ul class=\"small\">" + "".join(f"<li>{e(n)}</li>" for n in turn["notes"]) + "</ul>")
        parts.append("</section>")
    parts.append("</body></html>")
    return "\n".join(parts)


EXPORTERS = {
    "json": ("json", "application/json", lambda document: to_json(document)),
    "markdown": ("md", "text/markdown", to_markdown),
    "html": ("html", "text/html", to_html),
}


def safe_filename(title: str, extension: str) -> str:
    stem = "".join(ch if ch.isalnum() else "_" for ch in title.lower()).strip("_")
    stem = "_".join(part for part in stem.split("_") if part)[:50] or "conversation"
    return f"{stem}.{extension}"
